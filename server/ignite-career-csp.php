<?php
/** Plugin Name: IgniteCyber Academy Content Security Policy */
if (!defined('ABSPATH')) exit;

function icn_csp_nonce() {
    static $nonce;
    return $nonce ??= base64_encode(random_bytes(24));
}

function icn_csp_header($navigator = false) {
    $nonce = icn_csp_nonce();
    $script = $navigator ? ' https://challenges.cloudflare.com' : ' https://static.cloudflareinsights.com';
    $connect = $navigator ? ' https://challenges.cloudflare.com' : ' https://cloudflareinsights.com';
    $frames = $navigator ? ' https://challenges.cloudflare.com' : '';
    header("Content-Security-Policy: default-src 'self'; base-uri 'self'; object-src 'none'; "
        ."script-src 'self' 'nonce-$nonce'$script; script-src-attr 'none'; "
        ."style-src 'self' 'nonce-$nonce'; style-src-attr 'unsafe-inline'; "
        ."img-src 'self' data: blob:; font-src 'self' data:; connect-src 'self'$connect; "
        ."frame-src 'self' https://www.youtube-nocookie.com$frames; frame-ancestors 'self'; "
        ."form-action 'self'; worker-src 'self' blob:; manifest-src 'self'");
    header('Cache-Control: private, no-store, no-transform');
    header('X-Content-Type-Options: nosniff');
}

// WordPress-generated inline scripts are trusted at the API that emits them.
add_filter('wp_inline_script_attributes', function ($attributes) {
    if (!is_admin() && did_action('template_redirect')) $attributes['nonce'] = icn_csp_nonce();
    return $attributes;
});

add_action('template_redirect', function () {
    if (is_admin() || is_feed() || is_robots() || is_trackback()) return;
    $navigator = is_page('career-navigator');
    icn_csp_header($navigator);
    if (!$navigator) ob_start('icn_csp_nonce_head_styles');
}, 1);

// WordPress may insert global styles after wp_head. Process only the rendered head
// and only the style elements generated by the core and Academy theme.
function icn_csp_nonce_head_styles($html) {
    $end = stripos($html, '</head>');
    if ($end === false) return $html;
    $known = [
        'wp-img-auto-sizes-contain-inline-css', 'wp-emoji-styles-inline-css',
        'wp-block-library-inline-css', 'classic-theme-styles-inline-css',
        'global-styles-inline-css', 'athena-source-inline-css', 'ignite-career-navigation',
    ];
    $head = preg_replace_callback('~<style\b([^>]*?)>~i', function ($tag) use ($known) {
        if (!preg_match('~\bid=["\x27]([^"\x27]+)["\x27]~i', $tag[1], $id) ||
            !in_array($id[1], $known, true) || preg_match('~\bnonce\s*=~i', $tag[1])) {
            return $tag[0];
        }
        return '<style nonce="'.esc_attr(icn_csp_nonce()).'"'.$tag[1].'>';
    }, substr($html, 0, $end));
    return $head.substr($html, $end);
}
